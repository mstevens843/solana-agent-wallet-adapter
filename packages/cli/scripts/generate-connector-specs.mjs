#!/usr/bin/env node
// Bundles spec/connectors/*.connector.json into a TS module the CLI can import
// without traversing tsc's rootDir. Re-run on every build; emits a single file
// at packages/cli/src/forms/connectorSpecs.generated.ts.

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..', '..', '..');
const specDir = join(repoRoot, 'spec', 'connectors');
const outFile = join(__dirname, '..', 'src', 'forms', 'connectorSpecs.generated.ts');

const files = (await readdir(specDir))
  .filter((f) => f.endsWith('.connector.json'))
  .sort();

const specs = [];
for (const file of files) {
  const raw = JSON.parse(await readFile(join(specDir, file), 'utf8'));
  if (!raw.id) continue;
  specs.push({
    id: String(raw.id),
    name: String(raw.name ?? raw.id),
    aliases: Array.isArray(raw.aliases) ? raw.aliases : [],
    status: typeof raw.status === 'string' ? raw.status : 'live',
    requiredUserInputs: Array.isArray(raw.requiredUserInputs)
      ? raw.requiredUserInputs.map((i) => ({
          name: String(i.name),
          kind: String(i.kind ?? 'text'),
          required: Boolean(i.required),
          appliesTo: Array.isArray(i.appliesTo) ? i.appliesTo.map(String) : [],
          prompt: String(i.prompt ?? i.name ?? ''),
          options: Array.isArray(i.options) ? i.options.map(String) : undefined,
        }))
      : [],
    writeCapabilities: Array.isArray(raw.writeCapabilities)
      ? raw.writeCapabilities
          .filter((w) => w && w.actionKind)
          .map((w) => ({
            actionKind: String(w.actionKind),
            executionMode: String(w.executionMode ?? 'first_class_adapter'),
            implemented: Boolean(w.implemented),
            summary: String(w.prepares ?? ''),
          }))
      : [],
    readCapabilities: Array.isArray(raw.readCapabilities)
      ? raw.readCapabilities
          .filter((r) => r && r.toolName)
          .map((r) => ({
            toolName: String(r.toolName),
            implemented: Boolean(r.implemented),
            summary: String(r.returns ?? ''),
            source: String(r.source ?? 'first-class-adapter'),
            facts: Array.isArray(r.facts) ? r.facts.map(String) : [],
          }))
      : [],
  });
}

const header = `// AUTO-GENERATED by scripts/generate-connector-specs.mjs. Do not edit by hand.
// Source: spec/connectors/*.connector.json.
// Regenerate via: node packages/cli/scripts/generate-connector-specs.mjs

export interface ConnectorSpecInput {
  name: string;
  kind: string;
  required: boolean;
  appliesTo: string[];
  prompt: string;
  options?: string[];
}

export interface ConnectorWriteCapability {
  actionKind: string;
  executionMode: string;
  implemented: boolean;
  summary: string;
}

export interface ConnectorReadCapability {
  toolName: string;
  implemented: boolean;
  summary: string;
  source: string;
  facts: string[];
}

export interface ConnectorSpec {
  id: string;
  name: string;
  aliases: string[];
  status: string;
  requiredUserInputs: ConnectorSpecInput[];
  writeCapabilities: ConnectorWriteCapability[];
  readCapabilities: ConnectorReadCapability[];
}
`;

const body = `\nexport const CONNECTOR_SPECS: ConnectorSpec[] = ${JSON.stringify(specs, null, 2)};\n`;

await writeFile(outFile, header + body, 'utf8');
console.log(`Generated ${specs.length} connector specs → ${outFile}`);
